-- ─── 0. 전체 데이터 완전 삭제 ────────────────────────────────
truncate table personal_logs     restart identity cascade;
truncate table homework           restart identity cascade;
truncate table exercise_records   restart identity cascade;
truncate table sessions           restart identity cascade;

drop table if exists session_quality    cascade;
drop table if exists body_measurements  cascade;

-- ─── 1. 신규 테이블 생성 ─────────────────────────────────────

create table session_quality (
  id           uuid primary key default gen_random_uuid(),
  session_id   uuid not null references sessions(id) on delete cascade,
  core_score   integer check (core_score between 1 and 10),
  left_score   integer check (left_score between 1 and 10),
  right_score  integer check (right_score between 1 and 10),
  balance_note text,
  created_at   timestamptz default now(),
  unique (session_id)
);
alter table session_quality disable row level security;

create table body_measurements (
  id                 uuid primary key default gen_random_uuid(),
  member_id          uuid not null references members(id) on delete cascade,
  measured_at        date not null default current_date,
  weight_kg          numeric(5,1),
  skeletal_muscle_kg numeric(4,1),
  body_fat_kg        numeric(4,1),
  body_fat_pct       numeric(4,1),
  whr                numeric(4,3),
  bmr_kcal           integer,
  note               text,
  created_at         timestamptz default now()
);
alter table body_measurements disable row level security;
create index if not exists idx_body_member
  on body_measurements(member_id, measured_at desc);

